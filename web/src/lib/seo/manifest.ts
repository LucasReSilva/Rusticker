// Per-locale web app manifests (design D4). Pure, so it can be unit-tested;
// src/routes/manifest-[locale].webmanifest/+server.ts serves it.
import { m } from '$lib/paraglide/messages';
import type { Locale } from '$lib/paraglide/runtime';
import { localizedPath } from './urls';

// Manifests cannot reference CSS variables, so the colors are literal values,
// fixed by the shared contract (design D9).
/** Browser UI color: the Rust-orange primary of the light theme. */
export const THEME_COLOR = '#B65329';
/** Splash-screen background. */
export const BACKGROUND_COLOR = '#FFFFFF';

/** Icon files under `static/icons/`, generated by `bun run pwa:icons`. */
export const ICONS = [
	{ src: 'icons/pwa-192x192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
	{ src: 'icons/pwa-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
	{
		src: 'icons/maskable-icon-512x512.png',
		sizes: '512x512',
		type: 'image/png',
		purpose: 'maskable'
	}
] as const;

/** The Apple touch icon, linked from every page head. */
export const APPLE_TOUCH_ICON = 'icons/apple-touch-icon-180x180.png';

/** The manifest file of a locale, relative to the base path. */
export function manifestPath(locale: Locale): string {
	return `/manifest-${locale}.webmanifest`;
}

export type WebAppManifest = {
	id: string;
	name: string;
	short_name: string;
	description: string;
	lang: Locale;
	dir: 'ltr' | 'rtl';
	start_url: string;
	scope: string;
	display: 'standalone';
	theme_color: string;
	background_color: string;
	icons: Array<{ src: string; sizes: string; type: string; purpose: string }>;
};

/**
 * The manifest of a locale. Every locale shares `id` and `scope`, so the app
 * is the same one whichever locale it is installed from; only the texts,
 * `lang` and `start_url` (the locale's tool page) differ.
 */
export function buildManifest(locale: Locale, base: string): WebAppManifest {
	return {
		id: `${base}/`,
		name: m.pwa_name({}, { locale }),
		short_name: m.pwa_short_name({}, { locale }),
		description: m.pwa_description({}, { locale }),
		lang: locale,
		dir: 'ltr',
		start_url: `${base}${localizedPath('/', locale)}`,
		scope: `${base}/`,
		display: 'standalone',
		theme_color: THEME_COLOR,
		background_color: BACKGROUND_COLOR,
		icons: ICONS.map((icon) => ({ ...icon, src: `${base}/${icon.src}` }))
	};
}
